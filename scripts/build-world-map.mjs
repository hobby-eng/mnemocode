// Builds src/export/world-map-data.ts from the Natural Earth land polygons.
// Run it again only when assets/maps/ne_110m_land.geojson changes.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { robinson, WORLD_MAP_HEIGHT, WORLD_MAP_WIDTH } from '../dist/export/world-map.js';

const sourcePath = new URL('../assets/maps/ne_110m_land.geojson', import.meta.url);
const targetPath = new URL('../src/export/world-map-data.ts', import.meta.url);
const EXPECTED_SHA256 = '9e0729ee253ca7d7a5c4ae9395fb1902264c5377c52e224d13dd85010e2835d9';
/** Antarctica is left out: the sheet shows the inhabited continents only. */
const SOUTHERN_LIMIT = -60;
/** Shapes smaller than this many map units would print as specks. */
const MINIMUM_EXTENT = 6;

const bytes = readFileSync(sourcePath);
const digest = createHash('sha256').update(bytes).digest('hex');
if (digest !== EXPECTED_SHA256) throw new Error(`Unexpected map source: ${digest}`);

const paths = [];
for (const feature of JSON.parse(bytes.toString('utf8')).features) {
  const { type, coordinates } = feature.geometry;
  for (const polygon of type === 'Polygon' ? [coordinates] : coordinates) {
    const ring = polygon[0];
    if (Math.max(...ring.map(([, latitude]) => latitude)) < SOUTHERN_LIMIT) continue;
    const points = [];
    for (const [longitude, latitude] of ring) {
      const { x, y } = robinson(longitude, latitude);
      const point = [Math.round(x), Math.round(y)];
      const last = points.at(-1);
      if (last === undefined || last[0] !== point[0] || last[1] !== point[1]) points.push(point);
    }
    const xs = points.map(([x]) => x);
    const ys = points.map(([, y]) => y);
    const extent = Math.max(Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys));
    if (points.length < 4 || extent < MINIMUM_EXTENT) continue;
    paths.push(`M${points.map(([x, y]) => `${x} ${y}`).join('L')}Z`);
  }
}

writeFileSync(
  targetPath,
  `// Generated by scripts/build-world-map.mjs from assets/maps/ne_110m_land.geojson.
// Natural Earth land polygons, public domain. Do not edit by hand.
// Coordinates are Robinson projection units in a ${WORLD_MAP_WIDTH} x ${WORLD_MAP_HEIGHT} box, y downwards.
export const WORLD_MAP_LAND: readonly string[] = [
${paths.map((path) => `  '${path}',`).join('\n')}
];
`,
);
console.log(`Wrote ${paths.length} land shapes.`);
