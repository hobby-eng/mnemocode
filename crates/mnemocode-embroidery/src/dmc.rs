//! The colours are measured, not DMC's own: a thread looks as near to them as a screen shows it.

/// One thread: what a legend prints and what a pattern draws.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Thread {
    number: &'static str,
    name: &'static str,
    rgb: [u8; 3],
}

impl Thread {
    /// Its DMC number, such as `310`, `B5200` or `Blanc`.
    #[must_use]
    pub const fn number(&self) -> &'static str {
        self.number
    }

    /// Its colour's name in DMC's charts.
    #[must_use]
    pub const fn name(&self) -> &'static str {
        self.name
    }

    /// Its colour: red, green and blue bytes in sRGB.
    #[must_use]
    pub const fn rgb(&self) -> [u8; 3] {
        self.rgb
    }

    /// The place of its number among the others in a legend: numbers by their value first, then
    /// the named threads (B5200, Blanc, Ecru), as DMC's charts list them.
    #[must_use]
    pub fn order(&self) -> (u8, u32, &'static str) {
        self.number
            .parse::<u32>()
            .map_or((1, 0, self.number), |value| (0, value, ""))
    }
}

const fn thread(number: &'static str, name: &'static str, rgb: [u8; 3]) -> Thread {
    Thread { number, name, rgb }
}

