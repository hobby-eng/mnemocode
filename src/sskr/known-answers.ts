/** Transport and quorum refusals before every command; no engine, randomness or host is used. */
export function checkSskrTransportStartup(): void {
  expectSame(
    urToBytewords(SSKR_VECTOR.shares[0]),
    SSKR_VECTOR.firstShareBytewords,
    "SSKR published Bytewords",
  );
  // Every Byteword has four letters: run together they read as written apart (owner, 2026-10-13).
  expectSame(
    bytewordsToUr(SSKR_VECTOR.firstShareBytewords.replaceAll(" ", "")),
    SSKR_VECTOR.shares[0],
    "SSKR Bytewords run together",
  );
  expectSame(validateShareSet(SSKR_VECTOR.shares).length, 5, "SSKR official grouped quorum");
  for (const [name, shares] of [
    ["SSKR one complete group", SSKR_VECTOR.shares.slice(0, 2)],
    ["SSKR underfilled second group", SSKR_VECTOR.shares.slice(0, -1)],
  ] as const)
    expectRefused(() => validateShareSet(shares), /groups|threshold/u, name);
  expectRefused(
    () => validateShareSet([...SSKR_VECTOR.shares, SSKR_VECTOR.shares[0]]),
    /same SSKR member/u,
    "SSKR duplicate member",
  );
  expectRefused(
    () => validateShareSet([SSKR_VECTOR.shares[0], SSKR_SET_VECTOR.shares[0]]),
    /different sets/u,
    "SSKR mixed sets",
  );
  // ae is a valid Bytewords pair, but replacing the published checksum's last pair damages it.
  expectRefused(
    () => normalizeShare(`${SSKR_VECTOR.shares[0].slice(0, -2)}ae`),
    /checksum/u,
    "SSKR damaged transport checksum",
  );
}

/** A public share with one value byte changed and a correct transport CRC, for a digest refusal. */
function changedShareValue(): string {
  const bytes = urToTransport(SSKR_VECTOR.shares[0]);
  try {
    // Byte 8 is inside the value of this fixed official share, past its framing and metadata.
    bytes[8] = defined(bytes[8]) ^ 1;
    new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength).setUint32(
      bytes.length - CHECKSUM_BYTES,
      crc32(bytes.subarray(0, -CHECKSUM_BYTES)),
    );
    return transportToUr(bytes);
  } finally {
    bytes.fill(0);
  }
}

/** Public two-of-three fixture with group 1 outside its declared one-group set. */
function impossibleGroupQuorum(): string[] {
  return SSKR_SET_VECTOR.shares.slice(0, 2).map((record) => {
    const bytes = urToTransport(record);
    try {
      // This fixed 21-byte payload has one CBOR head byte; metadata byte 3 follows at byte 4.
      expectSame(defined(bytes[0]), 0x55, "SSKR metadata fixture framing");
      bytes[4] = (defined(bytes[4]) & 0x0f) | 0x10;
      new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength).setUint32(
        bytes.length - CHECKSUM_BYTES,
        crc32(bytes.subarray(0, -CHECKSUM_BYTES)),
      );
      // Reach the native boundary: normal transportToUr correctly refuses this metadata first.
      return SHARE_UNITS.ur.text(Array.from(bytes));
    } finally {
      bytes.fill(0);
    }
  });
}

/**
 * Every two of `shares`, each pair once, in order: with a threshold of two, as SSKR_SET_VECTOR has,
 * each pair must restore the set.
 */
export function sharePairs(shares: readonly string[]): [string, string][] {
  return shares.flatMap((first, place) =>
    shares.slice(place + 1).map((second): [string, string] => [first, second]),
  );
}

/**
 * The host's set of SSKR_SET_VECTOR's entropy, made with the public test-only `seed` in place of
 * randomness; the entropy and the seed are wiped whatever happens.
 */
async function testSet(platform: ShareSplitPlatform, seed: string): Promise<string[]> {
  const secret = bytesOfHex(SSKR_SET_VECTOR.entropy);
  const seedBytes = bytesOfHex(seed);
  try {
    return await platform.createShares(
      secret,
      SSKR_SET_VECTOR.threshold,
      SSKR_SET_VECTOR.count,
      seedBytes,
    );
  } finally {
    secret.fill(0);
    seedBytes.fill(0);
  }
}

/**
 * The host's creation of shares, checked by what it gives, as no published vector and no
 * implementation apart from the pinned library gives the shares of a seeded split (CORE-27):
 * every two of the shares made with the test-only seed restore the entropy, through the
 * combination that the official vectors checked first, and another seed makes other shares.
 */
async function checkCreation(platform: ShareSplitPlatform): Promise<void> {
  const created = await testSet(platform, SSKR_SET_VECTOR.testOnlySeed);
  expectSame(created.length, SSKR_SET_VECTOR.count, "SSKR creation share count");
  for (const pair of sharePairs(created))
    await expectRestored(platform, pair, SSKR_SET_VECTOR.entropy, "SSKR creation");
  const reseeded = await testSet(platform, SSKR_SET_VECTOR.otherTestOnlySeed);
  expectSame(
    reseeded.some((share) => created.includes(share)),
    false,
    "SSKR creation with another seed",
  );
}

/** The host's restoring of `shares` compared with `entropy`; `name` names the check. */
async function expectRestored(
  platform: ShareCombiner,
  shares: readonly string[],
  entropy: string,
  name: string,
): Promise<void> {
  const restored = await platform.combineShares(shares);
  try {
    if (hexOfBytes(restored) !== entropy)
      throw ERRORS.create("self-test-failed-no-secret-was-processed", [`${name}`]);
  } finally {
    restored.fill(0);
  }
}

/**
 * Compares the colour transport and the host's SSKR library with the known answers; throws, before
 * any secret is touched, at the first difference.
 */
export async function checkSskrKnownAnswers(platform: ShareSplitPlatform): Promise<void> {
  checkSskrTransportStartup();
  if (
    shareToColors(SSKR_VECTOR.shares[0]).join(" ") !== SSKR_VECTOR.firstShareColors.join(" ") ||
    colorsToShare(SSKR_VECTOR.firstShareColors.join(" ")) !== SSKR_VECTOR.shares[0]
  ) {
    throw ERRORS.create("sskr-color-known-answer-self-test-failed-no", []);
  }
  for (const share of SSKR_VECTOR.shares) {
    if (colorsToShare(shareToColors(share).join("")) !== normalizeShare(share))
      throw ERRORS.create("sskr-color-self-test-failed-no-secret-was", []);
  }
  await expectRestored(platform, SSKR_VECTOR.shares, SSKR_VECTOR.entropy, "SSKR recovery");
  await expectRestored(
    platform,
    SSKR_LONG_VECTOR.shares,
    SSKR_LONG_VECTOR.entropy,
    "SSKR 32-byte recovery",
  );
  await checkCreation(platform);
  for (const [name, shares] of [
    ["SSKR engine incomplete quorum", SSKR_VECTOR.shares.slice(0, -1)],
    ["SSKR engine damaged value", [changedShareValue(), ...SSKR_VECTOR.shares.slice(1)]],
    ["SSKR engine impossible group index", impossibleGroupQuorum()],
  ] as const)
    await expectRefusedLaterAs(
      async () => {
        const unexpected = await platform.combineShares(shares);
        unexpected.fill(0);
      },
      // The engine's refusal of a combination by its code, as every host gives it, whatever its
      // words: a decoding error or a failure of the host is another reason (AUD-037-BLD007).
      (error) => ShareCombineRefusalError.is(error),
      name,
    );
}
