import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { parseArguments } from "../src/cli/arguments.js";
import { runDecode } from "../src/cli/decode-command.js";
import { PrivatePage } from "../src/cli/private-page.js";
import { closingRows } from "../src/cli/private-screen.js";
import { CANCELLED } from "../src/cli/terminal-keys.js";
import { STYLE_CODES } from "../src/cli/terminal-style.js";
import { defined } from "../src/core/defined.js";
import { serializeRecord } from "../src/record.js";
import { CTRL_C, END, ENTER, HOME } from "./helpers/keys.js";
import { PrivateTerminal } from "./helpers/private-terminal.js";
import { DATE, LEGACY_VALID_MASKED, replacedAt, TEST_PHRASE } from "./helpers/test-phrase.js";

// The keys typed: `bytes`, all at once, or `answers`, each read in a turn of its own, as a person
// types answers one after the other; `terminal`, whether standard input and standard error count
// as a terminal, as --ask-secrets needs.
const typing = await vi.hoisted(async () => import("./helpers/typed-keys.js"));
vi.mock("../src/cli/terminal-input.js", async (original) =>
  typing.replacedTerminalInput(await original()),
);
const { keyboard } = typing;

// Public legacy-valid fixture from scripts/terminal_answers.py, not generated by the decoder.
const RECORD = serializeRecord("seedshift-legacy-valid", "indexes", LEGACY_VALID_MASKED);
const ARGS = ["--input", RECORD, "--date", DATE];
/** The last of the 128 candidates: the test phrase with "wrap" for its last word. */
const LAST_CANDIDATE = replacedAt(TEST_PHRASE, { 12: "wrap" });
let terminal: PrivateTerminal;

beforeEach(() => {
  terminal = new PrivateTerminal();
});
afterEach(() => {
  keyboard.terminal = false;
  keyboard.answers = [];
  terminal.close();
  vi.unstubAllEnvs();
});

/** The rows of what the terminal drew, each run of blanks as one space. */
function shown(): string[] {
  return terminal.frames().map((frame) => frame.replace(/\s+/gu, " ").trim());
}

describe("finite private legacy-valid candidate results", () => {
  it("makes the first and last of 128 exact public candidates reachable before clearing", async () => {
    keyboard.bytes = Array.from(Buffer.from(`${END}${HOME}${ENTER}`));
    await runDecode(parseArguments(ARGS));
    // The clear prompt comes under the candidates: they are read by pages first.
    expect(await PrivatePage.keepReadable(closingRows())).toBeUndefined();
    expect(shown().some((frame) => frame.includes(TEST_PHRASE))).toBe(true);
    expect(shown().some((frame) => frame.includes(LAST_CANDIDATE))).toBe(true);
    expect(shown().at(-2)).toContain(TEST_PHRASE);
    expect(shown().some((frame) => frame.includes("Each original fingerprint uses an"))).toBe(true);
  });

  it("shows the candidates as a result: a heading with facts, wrapped notes, grey fingerprint labels", async () => {
    vi.stubEnv("TERM", "xterm-256color");
    vi.stubEnv("NO_COLOR", "");
    vi.stubEnv("CLICOLOR_FORCE", "1");
    try {
      keyboard.bytes = [];
      await runDecode(parseArguments(ARGS));
    } finally {
      vi.unstubAllEnvs();
    }
    // Grey (SGR 90) labels, before the colour codes are taken out of what was written.
    expect(terminal.written).toContain("\x1b[90mOriginal fingerprint");
    const lines = terminal.written.replace(STYLE_CODES, "").split("\n");
    expect(lines).toEqual(
      expect.arrayContaining([
        "MnemoCode · Recovered candidates",
        expect.stringMatching(/^ {2}Mode {9}seedshift-legacy-valid$/u),
        expect.stringMatching(/^ {2}Input format +indexes$/u),
        expect.stringMatching(/^ {2}Candidates +128$/u),
        "Candidate 1 of 128",
        "Candidate 128 of 128",
        expect.stringMatching(/^ {2}Original fingerprint [0-9a-f]{8}$/u),
      ]),
    );
    // Only a phrase on one line, for copying, may be longer than running text.
    const phrase = /^(?:[a-z]+ ){11}[a-z]+$/u;
    for (const line of lines.filter((text) => !phrase.test(text)))
      expect(line.length, line).toBeLessThanOrEqual(78);
  });

  it("shows the candidates on a page of their own after the questions of --ask-secrets", async () => {
    vi.stubEnv("TERM", "xterm");
    keyboard.terminal = true;
    keyboard.answers = [`${RECORD}\r`, `${DATE}\r`];
    await runDecode(parseArguments(["--ask-secrets"]));
    const page = defined(terminal.frames().at(-1));
    expect(page.trimStart()).toMatch(/^MnemoCode · Recovered candidates\n/u);
    expect(page).toContain(TEST_PHRASE);
  });

  it("propagates cancellation instead of treating an unread result as done", async () => {
    keyboard.bytes = [CTRL_C.charCodeAt(0)];
    await runDecode(parseArguments(ARGS));
    expect(await PrivatePage.keepReadable(closingRows())).toBe(CANCELLED);
    expect(process.listenerCount("SIGWINCH")).toBe(0);
  });

  it("keeps redirected TSV complete and in its original order without consuming navigation", async () => {
    const raw: string[] = [];
    vi.spyOn(console, "log").mockImplementation((line: unknown) => raw.push(String(line)));
    Object.defineProperty(process.stdout, "isTTY", { configurable: true, value: false });
    keyboard.bytes = [];
    await runDecode(parseArguments(ARGS));
    expect(raw).toHaveLength(128);
    expect(raw.map((line) => Number(line.split("\t")[0]))).toEqual(
      Array.from({ length: 128 }, (_, place) => place + 1),
    );
    expect(raw[0]).toMatch(new RegExp(`^1\\t${TEST_PHRASE}\\t[0-9a-f]{8}$`, "u"));
    expect(raw[127]).toMatch(new RegExp(`^128\\t${LAST_CANDIDATE}\\t[0-9a-f]{8}$`, "u"));
    expect(terminal.written).not.toContain("Home/End");
    expect(terminal.written).toContain("The final column is the original BIP32 master fingerprint");
  });
});
